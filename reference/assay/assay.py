def from_metrics(metrics: Dict[str, float]) -> Dict:
    """Two-key / masking on published metric values when raw signals are not available (e.g. paper figures)."""
    c = _r4((metrics["CTS"] + metrics["PCS"] + (1 - metrics["BIS"]) + metrics["NSS"] + metrics["EPS"]) / 5)
    return {"metrics": metrics, "composite": c, "formula_verdict": verdict_of(c)}


def _vectors() -> Dict:
    out = {"formula_version": FORMULA_VERSION, "cases": []}
    for key, (sig, judge) in SAMPLES.items():
        if sig is None:
            continue
        for mode in ("code", "paper"):
            s = sig if mode == "code" else replace(sig, a_narr=round(1 - sig.s_fr, 4), jNSS=0.6)
            a = assay(s, judge, mode)
            out["cases"].append({"name": key, "mode": mode, "signals": asdict(s), "judge": judge,
                                 "metrics": a["metrics"], "composite": a["composite"],
                                 "formula_verdict": a["formula_verdict"], "two_key": a["two_key"]["state"],
                                 "ledger": {e["signal"]: round(e["amount"], 9) for e in a["ledger"]["entries"]},
                                 "opening": round(a["ledger"]["opening_balance"], 9),
                                 "tipping_min": a["tipping_point"]["min_distance"],
                                 "tipping_first": a["tipping_point"]["flips"][0]["signal"] if a["tipping_point"]["flips"] else None,
                                 "masking": a["masking"], "map": a["integrity_map"]})
    return out


