"""
ACHP Assay: reference implementation of the metric instruments (kit 11_THE_ASSAY.md).

Zero dependencies (stdlib only). This file is the source of truth; `assay.ts` is a line-for-line port and
`vectors.json` (generated by `python assay.py --vectors`) pins the two together.

Metric full forms (ACHP paper, Sec. IV):
  CTS  Consensus Truth Score           (higher = better supported)
  PCS  Perspective Completeness Score  (higher = more viewpoints present)
  BIS  Bias Impact Score               (higher = MORE bias; enters the composite as 1 - BIS)
  NSS  Narrative Stance Score          (higher = more neutral stance)
  EPS  Epistemic Position Score        (higher = better-calibrated certainty language)
  C    Composite = (CTS + PCS + (1 - BIS) + NSS + EPS) / 5

Two formula modes:
  "paper"  equations (1)-(6) exactly as published: narrative alignment and Judge NSS are independent inputs.
  "code"   what apps/api/achp/core/core_pipeline.py computes today: narrative alignment := 1 - framing,
           and Judge NSS falls back to NSS_proxy(BIS, framing) when the Judge omits it.

Instruments (all deterministic, all pure functions of the raw signals):
  compute()          metrics + composite + formula verdict (with clamp flags)
  ledger()           exact Shapley attribution of C against a declared reference sheet (double-entry: balances)
  tipping_point()    smallest single-signal change that flips the formula verdict (verdict robustness)
  two_key()          agreement between the Judge's verdict and the formula verdict
  masking()          narrative lift, Quiet Falsehood Index (QFI) and the masking flag
  leverage()         local sensitivity dC/dsignal and each signal's share of total leverage
  lineage()          which raw signals feed which metrics (fan-out, reuse)
  integrity_map_xy() coordinates + quadrant for the /runs Integrity Map
"""
