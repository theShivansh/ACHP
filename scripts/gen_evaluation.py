#!/usr/bin/env python3
"""Generate EVALUATION.md and the web app's benchmark data from reference/benchmark/results.json.

`/method` shows one headline number (07 section 8, 01_AUDIT G5). It is generated here, from one data file, so the
page, EVALUATION.md and the case page's Method drawer can never disagree. Nothing in the web app writes a benchmark
number by hand.

    python scripts/gen_evaluation.py            # write EVALUATION.md and apps/web/lib/benchmark.generated.json
    python scripts/gen_evaluation.py --check    # exit 1 if either file is out of date (for CI)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reference" / "benchmark" / "results.json"
MARKDOWN = ROOT / "EVALUATION.md"
WEB_JSON = ROOT / "apps" / "web" / "lib" / "benchmark.generated.json"


def load() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    cols = data["split_columns"]
    for s in data["systems"]:
        if len(s["scores"]) != len(cols):
            raise SystemExit(f"{s['name']}: {len(s['scores'])} scores for {len(cols)} columns")
    ours = [s for s in data["systems"] if s["name"] == data["headline"]["system"]]
    if len(ours) != 1 or ours[0]["scores"][-1] != data["headline"]["value"]:
        raise SystemExit("the headline must equal the Macro score of the named system")
    return data


def pct(v: float) -> str:
    return f"{v:.1f}%"


def markdown(d: dict) -> str:
    h = d["headline"]
    cols = d["split_columns"]
    out = [
        "# ACHP evaluation",
        "",
        f"ACHP reaches {pct(h['value'])} {h['metric']} on the project's own factual, opinion and prediction claims. "
        "These figures come from the project's own write-up and have not been re-run in this repository.",
        "",
        "_Generated by `scripts/gen_evaluation.py` from `reference/benchmark/results.json`. Do not edit by hand._",
        "",
        "## Accuracy by kind of claim",
        "",
        "| System | " + " | ".join(cols) + " |",
        "|---|" + "---|" * len(cols),
    ]
    for s in d["systems"]:
        cells = " | ".join(pct(v) for v in s["scores"])
        name = f"**{s['name']}**" if s.get("ours") else s["name"]
        out.append(f"| {name} | {cells} |")
    out += ["", "## What each part adds (macro accuracy)", "", "| Configuration | Macro accuracy |", "|---|---|"]
    for a in d["ablation"]:
        out.append(f"| {a['configuration']} | {pct(a['macro'])} |")
    out += ["", d["significance"], "", "## Other published figures", ""]
    for o in d["other_published"]:
        out.append(f"- **{o['label']}: {pct(o['value'])}.** {o['note']}")
    out += ["", "## Provenance", "", d["provenance"]["note"], ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = load()
    outputs = {MARKDOWN: markdown(data), WEB_JSON: json.dumps(data, indent=2, ensure_ascii=False) + "\n"}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
