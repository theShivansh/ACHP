#!/usr/bin/env python3
"""Generate EVALUATION.md and the web app's benchmark data.

Two sources, never mixed:
- bench/results/latest.json: ACHP Bench, measured in this repository by bench/run.py against a live backend and
  scored by bench/score.py from the stored event logs. This is the headline.
- reference/benchmark/results.json: the figures in the project's earlier write-up, which have not been re-run here.
  They are kept, labelled as such, and never averaged with the measured ones.

/method, the case page's Method drawer and EVALUATION.md all read what this script writes, so they cannot disagree.
Nothing in the web app writes a benchmark number by hand.

    python scripts/gen_evaluation.py            # write EVALUATION.md and apps/web/lib/benchmark.generated.json
    python scripts/gen_evaluation.py --check    # exit 1 if either file is out of date (for CI)
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "reference" / "benchmark" / "results.json"
MEASURED = ROOT / "bench" / "results" / "latest.json"
MARKDOWN = ROOT / "EVALUATION.md"
WEB_JSON = ROOT / "apps" / "web" / "lib" / "benchmark.generated.json"

CLASS_WORDS = {"supported": "Supported", "contradicted": "Refuted", "mixed": "Conflicting or cherry-picked", "unverifiable": "Not enough evidence"}
ACHP_WORDS = {"supported": "Supported", "contradicted": "Contradicted", "mixed": "Mixed or missing context", "unverifiable": "Unverifiable",
              "blocked": "Not checked", "no_verdict": "No verdict (the run failed)"}


def load_earlier() -> dict:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    cols = data["split_columns"]
    for s in data["systems"]:
        if len(s["scores"]) != len(cols):
            raise SystemExit(f"{s['name']}: {len(s['scores'])} scores for {len(cols)} columns")
    ours = [s for s in data["systems"] if s["name"] == data["headline"]["system"]]
    if len(ours) != 1 or ours[0]["scores"][-1] != data["headline"]["value"]:
        raise SystemExit("the earlier headline must equal the Macro score of the named system")
    return data


def load_measured() -> dict:
    m = json.loads(MEASURED.read_text(encoding="utf-8"))
    if "averitec" not in m.get("suites", {}):
        raise SystemExit("bench/results/latest.json has no AVeriTeC suite; run bench/run.py and bench/score.py")
    return m


def load() -> dict:
    m = load_measured()
    return {"measured": m, "earlier": load_earlier(), "complete": bool(m.get("completeness", {}).get("complete"))}


SUITE_WORDS = {"averitec": "real-world claims (AVeriTeC)", "safety": "injections and look-alikes", "metamorphic": "consistency pairs", "abstention": "claims nobody can check"}


def progress_lines(m: dict) -> list[str]:
    c = m["completeness"]
    lines = []
    for name, v in c["suites"].items():
        lines.append(f"- {SUITE_WORDS[name]}: {v['with_verdict']} of {v['planned']} have a verdict; "
                     f"{v['failed_model_quota']} stopped because the model quota ran out; {v['failed_other']} failed otherwise.")
    return lines


def pending_markdown(d: dict) -> str:
    m, e = d["measured"], d["earlier"]
    h = e["headline"]
    total = sum(v["planned"] for v in m["completeness"]["suites"].values())
    done = sum(v["with_verdict"] for v in m["completeness"]["suites"].values())
    quota = sum(v["failed_model_quota"] for v in m["completeness"]["suites"].values())
    out = [
        "# ACHP evaluation",
        "",
        f"ACHP reaches {h['value']:.1f}% {h['metric']} on the project's own factual, opinion and prediction claims, according to the project's earlier write-up. "
        "These figures have not been re-run in this repository. ACHP Bench, which measures the system end to end here, is part-way through and is not published until it is complete.",
        "",
        "_Generated by `scripts/gen_evaluation.py` from `reference/benchmark/results.json` and `bench/results/latest.json`. Do not edit by hand. How ACHP Bench works: `bench/README.md`._",
        "",
        "## ACHP Bench (in progress, not yet published)",
        "",
        f"{done} of {total} checks from run `{m['tag']}` have a verdict. "
        + (f"{quota} stopped when the backend's model quota ran out, before any agent could judge them. " if quota else "")
        + f"Results are published once every item has been tried and at least "
        f"{int(100 * m['completeness']['min_coverage_to_publish'])}% of each suite has a verdict, so that an outage is never reported as the method's accuracy.",
        "",
        *progress_lines(m),
    ]
    return "\n".join(out) + "\n" + earlier_markdown(e, heading="## Earlier figures (not re-run here)")


def pct(v: float | None, digits: int = 1) -> str:
    return "n/a" if v is None else f"{100 * v:.{digits}f}%"


def ci(w: dict) -> str:
    return f"{w['k']} of {w['n']} ({pct(w['rate'])}; 95% interval {pct(w['low'])} to {pct(w['high'])})"


TWO_KEY_WORDS = {"agree": "agree", "adjacent": "close calls", "split": "split decisions", "not_applicable": "not applicable (the Judge said Unverifiable)"}


def two_keys(counts: dict) -> str:
    return ", ".join(f"{counts[k]} {TWO_KEY_WORDS[k]}" for k in TWO_KEY_WORDS if counts.get(k))


def headline_sentence(m: dict) -> str:
    a = m["suites"]["averitec"]
    acc = a["accuracy"]
    return (
        f"On {a['n']} real-world claims checked by professional fact-checkers (a fixed, stratified sample of the AVeriTeC "
        f"dev set), ACHP's verdict matched the fact-checkers' label for {acc['k']} of {acc['n']}: "
        f"{pct(acc['rate'])} agreement on four labels (95% interval {pct(acc['low'])} to {pct(acc['high'])}). "
        f"Measured in this repository on {m['tag']} against the hosted backend; a run that failed counts as wrong."
    )


def earlier_markdown(e: dict, heading: str) -> str:
    out: list[str] = []
    cols = e["split_columns"]
    h = e["headline"]
    out += [
        "",
        heading,
        "",
        f"The project's earlier write-up reports {h['value']:.1f}% {h['metric']} on its own factual, opinion and prediction claims. "
        "Those claims and runs are not in this repository, so the figures below are transcribed, not measured, and are never averaged with ACHP Bench.",
        "",
        "| System | " + " | ".join(cols) + " |",
        "|---|" + "---|" * len(cols),
    ]
    for sys_ in e["systems"]:
        cells = " | ".join(f"{v:.1f}%" for v in sys_["scores"])
        name = f"**{sys_['name']}**" if sys_.get("ours") else sys_["name"]
        out.append(f"| {name} | {cells} |")
    out += ["", "| Configuration | Macro accuracy |", "|---|---|"]
    for ab_ in e["ablation"]:
        out.append(f"| {ab_['configuration']} | {ab_['macro']:.1f}% |")
    out += ["", e["significance"], ""]
    for o in e["other_published"]:
        out.append(f"- **{o['label']}: {o['value']:.1f}%.** {o['note']}")
    out += ["", e["provenance"]["note"], ""]
    return "\n".join(out)


def markdown(d: dict) -> str:
    if not d["complete"]:
        return pending_markdown(d)
    m, e = d["measured"], d["earlier"]
    a = m["suites"]["averitec"]
    ops = m["operations"]
    out = [
        "# ACHP evaluation",
        "",
        headline_sentence(m),
        "",
        "_Generated by `scripts/gen_evaluation.py` from `bench/results/latest.json` (ACHP Bench) and "
        "`reference/benchmark/results.json` (earlier figures). Do not edit by hand. How it was measured: `bench/README.md`._",
        "",
        "## ACHP Bench",
        "",
        f"Every check went through the public API exactly as the site sends it, and its full event log is stored under "
        f"`bench/runs/{m['tag']}/`. Scoring (`bench/score.py`) reads only those logs. Models: {', '.join(ops['models']) or 'n/a'}; "
        f"prompt version {', '.join(ops['prompt_versions']) or 'n/a'}; formula {m['formula_version']}.",
        "",
        "### Real-world claims (AVeriTeC)",
        "",
        f"- Agreement with the fact-checkers' label: {ci(a['accuracy'])}.",
        f"- Weighted back to the dev set's own mix of labels (mostly refuted claims): {pct(a['accuracy_weighted_to_dev_mix'])}.",
        f"- Macro-F1 over the four labels: {a['macro_f1']['value']:.3f} (95% interval {a['macro_f1']['low']:.3f} to {a['macro_f1']['high']:.3f}).",
        f"- A verdict was given for {ci(a['coverage'])}; when one was, it matched for {ci(a['accuracy_when_a_verdict_was_given'])}.",
        f"- Of the claims labelled Supported or Refuted, called the opposite (true called false, or false called true): {ci(a['true_false']['decisive_error'])}.",
        f"- Baselines on this sample: always the commonest label {pct(a['baselines']['always_the_commonest_label_in_this_sample'])}; "
        f"always 'not enough evidence' {pct(a['baselines']['always_unverifiable'])}; a uniform guess {pct(a['baselines']['uniform_random_expected'])}.",
        "",
        "| Fact-checkers said | " + " | ".join(ACHP_WORDS[k] for k in ACHP_WORDS) + " |",
        "|---|" + "---|" * len(ACHP_WORDS),
    ]
    for g in CLASS_WORDS:
        row = a["confusion"].get(g, {})
        out.append(f"| {CLASS_WORDS[g]} | " + " | ".join(str(row.get(k, 0)) for k in ACHP_WORDS) + " |")
    jf = a["judge_vs_formula"]
    out += [
        "",
        "#### The Judge and the formula, on the same claims",
        "",
        f"- The Judge's verdict matched for {ci(jf['judge_accuracy'])}.",
        f"- The formula's verdict (the reference Assay on the run's own five scores) matched for {ci(jf['formula_accuracy'])}. "
        "The formula has no 'not enough evidence', so it cannot be right on those claims.",
        f"- Two keys: {two_keys(jf['two_key'])}.",
        f"- Refuted claims the masking check flags (weak facts, formula at Mixed or better): {jf['refuted_claims_the_masking_check_flags']}.",
    ]
    s = m["suites"].get("safety")
    if s:
        out += ["", "### Injections and look-alikes", "",
                f"- Prompt injections blocked by the Gatekeeper: {ci(s['injections_blocked'])}.",
                f"- Ordinary claims that use words like 'ignore', 'system' or 'override', wrongly blocked: {ci(s['benign_wrongly_blocked'])}."]
    mm = m["suites"].get("metamorphic")
    if mm:
        out += ["", "### Consistency", "",
                f"- A claim and its negation got opposite verdicts in {ci(mm['negation_flips_when_both_decided'])} of the pairs where both got a true-or-false verdict.",
                f"- Two wordings of the same claim got the same verdict in {ci(mm['paraphrase_same_label'])} (without the cache: {ci(mm['paraphrase_same_label_without_cache'])}).",
                f"- On these settled facts, agreement with the expected label: {ci(mm['accuracy_on_settled_facts'])}."]
    ab = m["suites"].get("abstention")
    if ab:
        out += ["", "### Knowing when it cannot know", "",
                f"- Claims that cannot be checked (invented people, private events, the future, the unfalsifiable) called Unverifiable: {ci(ab['said_unverifiable'])}.",
                f"- Called true or false with strong confidence instead: {ci(ab['strong_true_or_false'])}."]
    gr = m["grounding"]
    out += ["", "### Grounding", "",
            f"- {gr['citations']} citations across {gr['runs']} checks; {gr['citations_to_a_source_not_in_the_log']} pointed to a source missing from the run's log.",
            f"- Parts labelled Supported or Contradicted with at least one cited source: {ci(gr['decisive_parts_with_a_cited_source'])}.",
            "", "### Running it", "",
            f"- {ops['runs']} checks: {ops['completed']} completed, {ops['failed']} failed (no verdict), {ops['other_no_verdict']} other.",
            f"- Completed on the first attempt: {ci(ops['first_attempt_completed'])}.",
            f"- Time per check, not from the cache: median {ops['seconds_per_check_p50']}s, 90th percentile {ops['seconds_per_check_p90']}s.",
            "",
            "### Limits",
            "",
            "- The claims are from 2020 to 2022 and their fact-checks are on the web; ACHP searches the web, so it can find them. This measures the system as deployed, search included.",
            "- The safety, consistency and abstention suites were written for this benchmark and labelled by one annotator. They test behaviour, not world knowledge.",
            "- One run per claim, on one day, against a free-tier deployment that can be slow or rate-limited; failures are counted, not hidden.",
            "- AVeriTeC is CC BY-NC 4.0 (Schlichtkrull et al., 2023); the sample in `bench/suites/averitec.jsonl` keeps its attribution.",
            ]

    return "\n".join(out) + "\n" + earlier_markdown(e, heading="## Earlier figures (not re-run here)")


def web(d: dict) -> dict:
    """What /method needs: the measured results (only once complete) without per-item id lists, and the earlier figures."""
    if not d["complete"]:
        c = d["measured"]["completeness"]
        return {"measured": None, "progress": {"tag": d["measured"]["tag"], "planned": sum(v["planned"] for v in c["suites"].values()),
                                               "with_verdict": sum(v["with_verdict"] for v in c["suites"].values())}, "earlier": d["earlier"]}
    m = json.loads(json.dumps(d["measured"]))
    m["headline_sentence"] = headline_sentence(d["measured"])
    for s in m["suites"].values():
        for k in [k for k in s if k.endswith("_ids") or k in ("pairs", "injections_not_blocked")]:
            s.pop(k)
    return {"measured": m, "earlier": d["earlier"]}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    data = load()
    outputs = {MARKDOWN: markdown(data), WEB_JSON: json.dumps(web(data), indent=2, ensure_ascii=False) + "\n"}
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8").replace("\r\n", "\n") != text]
    if args.check:
        for p in stale:
            print(f"out of date: {p.relative_to(ROOT)}")
        return 1 if stale else 0
    for p, text in outputs.items():
        p.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
